            ],
        ];

        // Clean out existing services to remove redundancies and insert the 6 unique core services
        Service::query()->delete();

        foreach ($servicesData as $item) {
            $subFeatures = $item['sub_features'] ?? [];
            $pricingTiers = $item['pricing_tiers'] ?? [];
            $faqs = $item['faqs'] ?? [];

            unset($item['sub_features'], $item['pricing_tiers'], $item['faqs']);

            $service = Service::create($item);

            // Seed sub-features
            foreach ($subFeatures as $index => $feature) {
                ServiceFeature::create([
                    'service_id' => $service->id,
                    'title' => $feature['title'],
                    'description' => $feature['description'],
                    'icon' => $feature['icon'] ?? 'sparkles',
                    'badge' => $feature['badge'] ?? null,
                    'sort_order' => $index + 1,
                ]);
            }

            // Seed pricing tiers
            foreach ($pricingTiers as $index => $tier) {
                ServicePricingTier::create([
                    'service_id' => $service->id,
                    'name' => $tier['name'],
                    'price' => $tier['price'],
                    'note' => $tier['note'] ?? null,
                    'sort_order' => $index + 1,
                ]);
            }

            // Seed FAQs
            foreach ($faqs as $index => $faq) {
                ServiceFaq::create([
                    'service_id' => $service->id,
                    'question' => $faq['question'],
                    'answer' => $faq['answer'],
                    'sort_order' => $index + 1,
                ]);
            }
        }
